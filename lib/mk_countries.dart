/// نام برای تطبیق: آ/أ/إ ⇒ ا، ي/ئ ⇒ ی، ك ⇒ ک، ة ⇒ ه، بدون فاصله/نیم‌فاصله/خط تیره/نقطه، حروف کوچک.
String mkCountryNorm(String s) => s
    .replaceAll(RegExp('[آأإ]'), 'ا')
    .replaceAll(RegExp('[يئ]'), 'ی')
    .replaceAll('ك', 'ک')
    .replaceAll('ة', 'ه')
    .replaceAll('ؤ', 'و')
    .replaceAll(RegExp(r"[\s‌‎‏\-_.'ـ]"), '')
    .toLowerCase();

final Map<String, String> _kIndex = <String, String>{
  for (final MapEntry<String, List<String>> e in kMkCountryNames.entries) ...<String, String>{
    mkCountryNorm(e.key): e.key,
    for (final String n in e.value) mkCountryNorm(n): e.key,
  },
};

/// نام یا کد کشور ⇒ کد ISO دوحرفی (بزرگ)، یا null اگر شناخته نشد.
String? mkCountryKey(String raw) {
  final String n = mkCountryNorm(raw.trim());
  if (n.isEmpty) return null;
  final String? hit = _kIndex[n];
  if (hit != null) return hit;
  // «جمهوری …» / «کشور …» / «پادشاهی …»
  for (final String p in <String>['جمهوری', 'کشور', 'پادشاهی', 'republicof', 'kingdomof', 'the']) {
    final String pn = mkCountryNorm(p);
    if (n.startsWith(pn) && n.length > pn.length) {
      final String? h = _kIndex[n.substring(pn.length)];
      if (h != null) return h;
    }
  }
  return null;
}
